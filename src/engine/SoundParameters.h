enum class Codec { Direct, Voices, Free, Sync, SyncT4 };
enum class Kind { Integer, Boolean, Choice };
struct Parameter {
    unsigned index;
    const char* symbol;
    const char* name;
    const char* group;
    int field;
    int minimum, maximum, defaultValue;
    LabelKind label;
    Codec codec;
    int pair; // -1 or permanent tempo-pair ordinal
    int modeField; // storage binding of the pair's FREE/SYNC switch, -1 otherwise
    Kind kind;
};
const std::array<Parameter, kParameterCount>& parameters();
const Parameter* parameter(unsigned index);
inline const Parameter* parameter(ParameterId id) {
    return parameter(static_cast<unsigned>(id));
}
// Resolve a panel's field to its permanent identity in the requested mode.
const Parameter* parameterForField(int field, bool synced = false);
bool canonicalize(const Parameter&, double input, int& output);
int read(const Parameter&, const Program&);
// Writes only this codec's field. Mode/cache policy belongs to the caller.
bool write(const Parameter&, Program&, double value);
double normalize(const Parameter&, int value);
std::string choiceLabel(const Parameter&, int value);
